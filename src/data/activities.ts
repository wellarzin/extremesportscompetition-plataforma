// Generate daily activity data for the chart (last 30 days)
export const generateDailyActivityData = (_userId: string) => {
  const data = [];
  const baseDate = new Date('2025-05-18');
  for (let i = 29; i >= 0; i--) {
    const date = new Date(baseDate);
    date.setDate(date.getDate() - i);
    const dateStr = date.toISOString().split('T')[0];
    const dayOfWeek = date.getDay();
    const isRestDay = dayOfWeek === 0; // Sunday rest
    const activitiesCount = isRestDay ? 0 : Math.floor(Math.random() * 3) + (Math.random() > 0.3 ? 1 : 0);
    data.push({
      date: dateStr,
      label: `${date.getDate()}/${date.getMonth() + 1}`,
      activities: activitiesCount,
      points: activitiesCount * (Math.floor(Math.random() * 50) + 60),
      duration: activitiesCount * (Math.floor(Math.random() * 30) + 20),
    });
  }
  return data;
};
